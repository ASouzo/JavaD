package entity;

import java.util.Date;

/**
 *
 * @author Abderrazekbenhamouda
 */
public class Adopt {
    
    private int id,idUser,idAnimal;
    private Date date ;
    private String etat ;

    public int getId() {
        return id;
    }

    public void setId(int id) {
        this.id = id;
    }

    public int getIdUser() {
        return idUser;
    }

    public void setIdUser(int idUser) {
        this.idUser = idUser;
    }

    public int getIdAnimal() {
        return idAnimal;
    }

    public void setIdAnimal(int idAnimal) {
        this.idAnimal = idAnimal;
    }

    public Date getDate() {
        return date;
    }

    public void setDate(Date date) {
        this.date = date;
    }

    public String getEtat() {
        return etat;
    }

    public void setEtat(String etat) {
        this.etat = etat;
    }

    @Override
    public String toString() {
        return "Adopt{" + "id=" + id + ", idUser=" + idUser + ", idAnimal=" + idAnimal + ", date=" + date + ", etat=" + etat + '}';
    }


    
}
